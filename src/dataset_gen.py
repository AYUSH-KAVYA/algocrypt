"""
Synthetic Cryptographic Dataset Generation Pipeline.

Generates labeled datasets of ciphertexts and hash digests generated by various
modern cryptographic algorithms (AES-ECB, AES-CBC, DES-CBC, RC4, MD5, SHA-256)
across diverse plaintext types (repeated, structured, short, natural_text, random).
"""

import argparse
import os
import random
import string
import uuid
from typing import Dict, List, Any, Tuple
import pandas as pd

from Crypto.Cipher import AES, DES, ARC4
from Crypto.Hash import MD5, SHA256
from Crypto.Random import get_random_bytes
from Crypto.Util.Padding import pad


# Target Algorithm Configuration
TARGET_ALGORITHMS = {
    "AES-ECB": {"category": "block_16", "block_size": 16},
    "AES-CBC": {"category": "block_16", "block_size": 16},
    "DES-CBC": {"category": "block_8", "block_size": 8},
    "RC4": {"category": "stream", "block_size": 1},
    "MD5": {"category": "hash", "block_size": 1},
    "SHA-256": {"category": "hash", "block_size": 1},
}

PLAINTEXT_TYPES = ["repeated", "structured", "short", "natural_text", "random"]


class PlaintextGenerator:
    """Generates diverse plaintext payloads to expose implementation/metadata artifacts."""

    STRUCTURED_TEMPLATES = [
        '{"user_id": 10042, "status": "active", "roles": ["admin", "developer"], "session": "token_abc_1234567890"}',
        '<html><head><title>Test Page</title></head><body><h1>Welcome</h1><p>Standard boilerplate payload.</p></body></html>',
        'POST /api/v1/resource HTTP/1.1\r\nHost: example.com\r\nContent-Type: application/json\r\n\r\n{"data":"test"}',
        '<response><status>200</status><message>Operation completed successfully</message><id>987654321</id></response>',
        'LOG [2026-09-08 23:45:00] INFO com.example.service.AuthEngine: User authentication succeeded for session_id=89234',
    ]

    NATURAL_TEXT_SAMPLES = [
        "Cryptography is the practice and study of techniques for secure communication in the presence of adversarial third parties.",
        "The quick brown fox jumps over the lazy dog. Pack my box with five dozen liquor jugs. How vexingly quick daft zebras jump!",
        "def compute_hash(data: bytes) -> str:\n    import hashlib\n    return hashlib.sha256(data).hexdigest()\n",
        "Artificial intelligence and machine learning models can identify subtle structural patterns in encrypted data streams.",
        "Security is a process, not a product. Implementation details matter far more than theoretical cipher security alone.",
    ]

    @classmethod
    def generate(cls, ptype: str, target_len: int = 128) -> bytes:
        """Generate bytes for the requested plaintext type."""
        if ptype == "repeated":
            # Exposes ECB mode repeated-block vulnerability
            pattern_choice = random.choice([1, 2, 3, 4])
            if pattern_choice == 1:
                return b"\x00" * target_len
            elif pattern_choice == 2:
                return b"A" * target_len
            elif pattern_choice == 3:
                chunk = b"ABCDEF1234567890"  # Exactly 16 bytes pattern
                return (chunk * (target_len // len(chunk) + 1))[:target_len]
            else:
                chunk = b"DEADBEEF"  # 8 bytes pattern
                return (chunk * (target_len // len(chunk) + 1))[:target_len]

        elif ptype == "structured":
            base = random.choice(cls.STRUCTURED_TEMPLATES).encode("utf-8")
            if len(base) < target_len:
                base = base * (target_len // len(base) + 1)
            return base[:target_len]

        elif ptype == "short":
            # Plaintexts smaller than 16 bytes to force heavy padding
            short_len = random.randint(1, 15)
            return get_random_bytes(short_len)

        elif ptype == "natural_text":
            base = random.choice(cls.NATURAL_TEXT_SAMPLES).encode("utf-8")
            if len(base) < target_len:
                base = base * (target_len // len(base) + 1)
            return base[:target_len]

        elif ptype == "random":
            return get_random_bytes(target_len)

        else:
            raise ValueError(f"Unknown plaintext type: {ptype}")


class CryptoEngine:
    """Wrapper around PyCryptodome primitives with random key/IV generation."""

    @staticmethod
    def encrypt_sample(algo: str, plaintext: bytes) -> bytes:
        """Encrypt or hash the given plaintext using the target algorithm."""
        if algo == "AES-ECB":
            key = get_random_bytes(16)
            cipher = AES.new(key, AES.MODE_ECB)
            padded_pt = pad(plaintext, AES.block_size, style="pkcs7")
            return cipher.encrypt(padded_pt)

        elif algo == "AES-CBC":
            key = get_random_bytes(16)
            iv = get_random_bytes(16)
            cipher = AES.new(key, AES.MODE_CBC, iv=iv)
            padded_pt = pad(plaintext, AES.block_size, style="pkcs7")
            return cipher.encrypt(padded_pt)

        elif algo == "DES-CBC":
            key = get_random_bytes(8)
            iv = get_random_bytes(8)
            cipher = DES.new(key, DES.MODE_CBC, iv=iv)
            padded_pt = pad(plaintext, DES.block_size, style="pkcs7")
            return cipher.encrypt(padded_pt)

        elif algo == "RC4":
            key = get_random_bytes(16)
            cipher = ARC4.new(key)
            return cipher.encrypt(plaintext)

        elif algo == "MD5":
            hasher = MD5.new()
            hasher.update(plaintext)
            return hasher.digest()

        elif algo == "SHA-256":
            hasher = SHA256.new()
            hasher.update(plaintext)
            return hasher.digest()

        else:
            raise ValueError(f"Unsupported algorithm: {algo}")


def generate_dataset(num_samples: int = 1200, seed: int = 42) -> pd.DataFrame:
    """Generate a balanced synthetic dataset across algorithms and plaintext types."""
    random.seed(seed)
    records: List[Dict[str, Any]] = []
    
    algos = list(TARGET_ALGORITHMS.keys())
    samples_per_algo = num_samples // len(algos)

    for algo in algos:
        meta = TARGET_ALGORITHMS[algo]
        for i in range(samples_per_algo):
            # Select plaintext type evenly
            ptype = PLAINTEXT_TYPES[i % len(PLAINTEXT_TYPES)]
            
            # Vary plaintext length (between 16 and 512 bytes, except for 'short')
            if ptype == "short":
                pt_len = random.randint(1, 15)
            else:
                pt_len = random.choice([32, 64, 128, 256, 512, 1024])
            
            plaintext = PlaintextGenerator.generate(ptype, target_len=pt_len)
            ciphertext_bytes = CryptoEngine.encrypt_sample(algo, plaintext)
            
            records.append({
                "sample_id": str(uuid.uuid4()),
                "ciphertext_hex": ciphertext_bytes.hex(),
                "ciphertext_bytes_len": len(ciphertext_bytes),
                "label": algo,
                "category": meta["category"],
                "plaintext_type": ptype,
                "plaintext_len": len(plaintext),
            })

    df = pd.DataFrame(records)
    # Shuffle dataset
    return df.sample(frac=1, random_state=seed).reset_index(drop=True)


def validate_dataset(df: pd.DataFrame) -> Tuple[bool, List[str]]:
    """Validate output data integrity and verify cryptographic fingerprints."""
    issues = []
    
    # 1. Check total count and label distribution
    label_counts = df["label"].value_counts().to_dict()
    print(f"[Validation] Dataset sample count: {len(df)}")
    print(f"[Validation] Label distribution: {label_counts}")
    
    if len(label_counts) != len(TARGET_ALGORITHMS):
        issues.append(f"Expected {len(TARGET_ALGORITHMS)} unique labels, got {len(label_counts)}")

    # 2. Verify AES-ECB exhibits duplicate 16-byte blocks on repeated plaintexts
    ecb_repeated = df[(df["label"] == "AES-ECB") & (df["plaintext_type"] == "repeated")]
    ecb_duplicates_found = 0
    for _, row in ecb_repeated.iterrows():
        ct_hex = row["ciphertext_hex"]
        # Split into 32-char (16-byte) hex blocks
        blocks = [ct_hex[i:i+32] for i in range(0, len(ct_hex), 32)]
        if len(blocks) != len(set(blocks)):
            ecb_duplicates_found += 1
            
    print(f"[Validation] AES-ECB repeated plaintext samples with duplicate blocks: {ecb_duplicates_found}/{len(ecb_repeated)}")
    if len(ecb_repeated) > 0 and ecb_duplicates_found == 0:
        issues.append("AES-ECB on repeated plaintexts failed to produce duplicate 16-byte blocks!")

    # 3. Verify MD5 & SHA-256 fixed byte lengths
    md5_samples = df[df["label"] == "MD5"]
    if not (md5_samples["ciphertext_bytes_len"] == 16).all():
        issues.append("MD5 samples contain invalid byte lengths (expected strictly 16 bytes)")

    sha256_samples = df[df["label"] == "SHA-256"]
    if not (sha256_samples["ciphertext_bytes_len"] == 32).all():
        issues.append("SHA-256 samples contain invalid byte lengths (expected strictly 32 bytes)")

    # 4. Verify Block Alignment
    aes_cbc_samples = df[df["label"] == "AES-CBC"]
    if not (aes_cbc_samples["ciphertext_bytes_len"] % 16 == 0).all():
        issues.append("AES-CBC sample lengths are not all multiples of 16 bytes")

    des_cbc_samples = df[df["label"] == "DES-CBC"]
    if not (des_cbc_samples["ciphertext_bytes_len"] % 8 == 0).all():
        issues.append("DES-CBC sample lengths are not all multiples of 8 bytes")

    is_valid = len(issues) == 0
    return is_valid, issues


def main():
    parser = argparse.ArgumentParser(description="Cryptographic Dataset Generation Pipeline")
    parser.add_argument("--num-samples", type=int, default=1200, help="Total number of dataset samples to generate")
    parser.add_argument("--output", type=str, default="data/dataset.csv", help="Output file path (.csv or .parquet)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    parser.add_argument("--validate", action="store_true", help="Run automated cryptographic output validation")
    
    args = parser.parse_args()

    print(f"[*] Generating {args.num_samples} synthetic cryptographic dataset samples...")
    df = generate_dataset(num_samples=args.num_samples, seed=args.seed)

    # Ensure output directory exists
    os.makedirs(os.path.dirname(args.output), exist_ok=True)

    if args.output.endswith(".parquet"):
        df.to_parquet(args.output, index=False)
    else:
        df.to_csv(args.output, index=False)
        
    print(f"[+] Dataset successfully exported to {args.output}")

    if args.validate:
        print("[*] Running automated validation checks...")
        valid, issues = validate_dataset(df)
        if valid:
            print("[✓] All dataset validation checks PASSED!")
        else:
            print("[✗] Validation FAILED with issues:")
            for issue in issues:
                print(f"  - {issue}")


if __name__ == "__main__":
    main()
